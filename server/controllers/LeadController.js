const getLeads = async (req, res) => {
  try {
    const { search, country, currency, stage, owner } = req.query;

    const filter = {};

    // Full-text search across name, company, email, phone
    // (works because we added a text index on those fields in the model)
    if (search && search.trim()) {
      filter.$text = { $search: search.trim() };
    }

    if (country)  filter.country  = country;
    if (currency) filter.currency = currency;
    if (stage)    filter.stage    = stage;
    if (owner)    filter.owner    = owner;

    // Ã¢â€â‚¬Ã¢â€â‚¬ Pagination Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬
    const page  = Math.max(1, parseInt(req.query.page)  || 1);
    const limit = Math.min(100, Math.max(1, parseInt(req.query.limit) || 20));
    const skip  = (page - 1) * limit;

    // Run the query and the count in parallel (faster than two sequential calls)
    const [leads, total] = await Promise.all([
      Lead.find(filter)
        .populate("owner", "name email role") // show owner details, not just id
        .sort({ createdAt: -1 })              // newest first
        .skip(skip)
        .limit(limit),
      Lead.countDocuments(filter),
    ]);

    res.json({
      success: true,
      leads,
      pagination: {
        total,                              // total matching documents
        page,
        limit,
        pages: Math.ceil(total / limit),   // total number of pages
      },
    });
  } catch (err) {
    console.error("getLeads error:", err);
    res.status(500).json({ success: false, message: "Server error." });
  }
};


