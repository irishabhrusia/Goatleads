// Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬
const updateLead = async (req, res) => {
  try {
    const lead = await Lead.findById(req.params.id);

    if (!lead) {
      return res.status(404).json({ success: false, message: "Lead not found." });
    }

    // Reps can only edit their own leads
    if (
      req.user.role === ROLES.REP &&
      lead.owner.toString() !== req.user._id.toString()
    ) {
      return res.status(403).json({ success: false, message: "You can only edit your own leads." });
    }

    // Fields that are allowed to be updated
    const previousStage = lead.stage;

    const allowed = [
      "name", "company", "email", "phone",
      "country", "currency", "amount",
      "stage", "owner", "lostReason",
    ];

    // Apply only the fields that were sent in the request body
    allowed.forEach((field) => {
      if (req.body[field] !== undefined) {
        lead[field] = req.body[field];
      }
    });

    // Validate enums after applying changes
    if (!COUNTRIES.includes(lead.country))
      return res.status(400).json({ success: false, message: `country must be one of: ${COUNTRIES.join(", ")}.` });

    if (!CURRENCIES.includes(lead.currency))
      return res.status(400).json({ success: false, message: `currency must be one of: ${CURRENCIES.join(", ")}.` });

    if (!STAGE_LIST.includes(lead.stage))
      return res.status(400).json({ success: false, message: `stage must be one of: ${STAGE_LIST.join(", ")}.` });

    // Recalculate amountBase whenever amount or currency changed
    const rates = await getRates();
    lead.amountBase = convertToBase(lead.amount, lead.currency, rates);

    await lead.save();
    await lead.populate("owner", "name email role");

    if (previousStage !== lead.stage) {
      await logActivity({
        lead: lead._id,
        user: req.user._id,
        type: ACTIVITY_TYPES.STAGE_CHANGE,
        content: `Moved stage from "${previousStage}" to "${lead.stage}"`,
        metadata: {
          fromStage: previousStage,
          toStage: lead.stage,
          lostReason: lead.lostReason || "",
        },
      });
    }

    res.json({ success: true, message: "Lead updated.", lead });
  } catch (err) {
    console.error("updateLead error:", err);
    res.status(500).json({ success: false, message: "Server error." });
  }
};

