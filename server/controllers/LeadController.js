// PATCH /api/leads/:id/stage
// The dedicated Kanban-move endpoint. Only updates stage (and lostReason).
// Keeping this separate from PUT /api/leads/:id makes the Kanban board simple:
// it only sends { stage } (plus lostReason when needed), nothing else.
const updateStage = async (req, res) => {
  try {
    const { stage, lostReason } = req.body;

    // Validate the incoming stage value
    if (!stage) {
      return res.status(400).json({ success: false, message: "stage is required." });
    }
    if (!STAGE_LIST.includes(stage)) {
      return res.status(400).json({
        success: false,
        message: `stage must be one of: ${STAGE_LIST.join(", ")}.`,
      });
    }

    const lead = await Lead.findById(req.params.id);
    if (!lead) {
      return res.status(404).json({ success: false, message: "Lead not found." });
    }

    // Reps can only move their own leads
    if (
      req.user.role === ROLES.REP &&
      lead.owner.toString() !== req.user._id.toString()
    ) {
      return res.status(403).json({ success: false, message: "You can only update your own leads." });
    }

    // Moving to "Closed Lost" requires a reason -- the dashboard needs this data
    if (stage === STAGES.CLOSED_LOST && !(lostReason || "").trim()) {
      return res.status(400).json({
        success: false,
        message: "lostReason is required when marking a lead as Closed Lost.",
      });
    }

    const previousStage = lead.stage;
    lead.stage = stage;

    // Set lostReason when moving to Closed Lost, clear it for every other stage
    lead.lostReason = stage === STAGES.CLOSED_LOST ? lostReason.trim() : "";

    await lead.save();
    await lead.populate("owner", "name email role");

    if (previousStage !== stage) {
      await logActivity({
        lead: lead._id,
        user: req.user._id,
        type: ACTIVITY_TYPES.STAGE_CHANGE,
        content: `Moved stage from "${previousStage}" to "${stage}"`,
        metadata: {
          fromStage: previousStage,
          toStage: stage,
          lostReason: lead.lostReason || "",
        },
      });
    }

    res.json({ success: true, message: "Stage updated.", lead });
  } catch (err) {
    console.error("updateStage error:", err);
    res.status(500).json({ success: false, message: "Server error." });
  }
};

